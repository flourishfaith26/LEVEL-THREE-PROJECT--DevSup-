const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const CANDIDATE_MODELS = [
    process.env.GEMINI_MODEL,
    'gemini-3.1-flash-lite',
    'gemini-flash-latest',
    'gemini-flash-lite-latest',
    'gemini-2.5-flash'
].filter(Boolean);

export async function askGemini(prompt, conversationContext = '') {
    if (!GEMINI_API_KEY) {
        throw new Error('Gemini API key is not configured.');
    }

    const systemInstruction = `You are DevSup AI, an elite, helpful software engineering AI assistant integrated directly into DevSup — the developer collaboration platform.
Your goals:
1. Provide accurate, production-ready code solutions, bug fixes, and architectural advice.
2. When debugging stack traces or errors, explain the root cause and provide the exact corrected code block.
3. Keep prose direct, concise, and developer-friendly. Always format code using markdown backticks with the language tag (e.g. \`\`\`javascript or \`\`\`python).
4. If asked to summarize discussions or code, provide crisp bullet points.`;

    const fullPrompt = conversationContext 
        ? `${systemInstruction}\n\nRecent Channel Context:\n${conversationContext}\n\nDeveloper Request:\n${prompt}`
        : `${systemInstruction}\n\nDeveloper Request:\n${prompt}`;

    let lastError = null;

    for (const model of CANDIDATE_MODELS) {
        try {
            const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${GEMINI_API_KEY}`;
            const controller = new AbortController();
            const timeout = setTimeout(() => controller.abort(), 12000);

            const response = await fetch(endpoint, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                signal: controller.signal,
                body: JSON.stringify({
                    contents: [{
                        parts: [{ text: fullPrompt }]
                    }],
                    generationConfig: {
                        temperature: 0.3,
                        maxOutputTokens: 2048
                    }
                })
            });
            clearTimeout(timeout);

            const data = await response.json();
            if (response.ok && data.candidates?.[0]?.content?.parts?.[0]?.text) {
                return data.candidates[0].content.parts[0].text.trim();
            }

            const errMsg = data.error?.message || `Model ${model} returned status ${response.status}`;
            console.warn(`[DevSup AI] Model ${model} failed, trying next candidate:`, errMsg);
            lastError = new Error(errMsg);
        } catch (e) {
            console.warn(`[DevSup AI] Model ${model} exception:`, e.message);
            lastError = e;
        }
    }

    throw lastError || new Error('No response generated by DevSup AI.');
}

/**
 * POST /api/ai/ask
 * Body: { prompt, context, codeSnippet }
 */
router.post('/ask', async (req, res) => {
    try {
        const { prompt, context, codeSnippet } = req.body;
        if (!prompt && !codeSnippet) {
            return res.status(400).json({ error: 'Prompt or code snippet is required.' });
        }

        let combinedPrompt = prompt || '';
        if (codeSnippet) {
            combinedPrompt += `\n\nCode snippet provided:\n\`\`\`\n${codeSnippet}\n\`\`\``;
        }

        const reply = await askGemini(combinedPrompt, context);
        res.json({ reply, model: 'gemini-3.1-flash-lite' });
    } catch (err) {
        console.warn('AI ask route using fallback answer generator:', err.message);
        const fallbackReply = generateSmartDevSupAiAnswer(req.body.prompt || '', req.body.context || '');
        res.json({ reply: fallbackReply, model: 'devsup-ai-engine', fallback: true });
    }
});

/**
 * POST /api/ai/explain-code
 * Body: { code, language }
 */
router.post('/explain-code', async (req, res) => {
    try {
        const { code, language } = req.body;
        if (!code) {
            return res.status(400).json({ error: 'Code is required.' });
        }

        const prompt = `Please explain this ${language || ''} code snippet clearly and concisely. Highlight how it works, potential edge cases, and any performance or security improvements:\n\n\`\`\`${language || ''}\n${code}\n\`\`\``;

        const reply = await askGemini(prompt);
        res.json({ reply, model: 'gemini-3.1-flash-lite' });
    } catch (err) {
        console.warn('Explain code route using fallback generator:', err.message);
        const explanation = `### 📘 Code Overview (${(req.body.language || 'code').toUpperCase()})\n\n1. **Core Logic:** The snippet initializes execution variables and processes inputs through algorithmic flow.\n2. **Complexity:** Executes within anticipated time bounds relative to data size.\n3. **Recommendations:** Verify boundary checks (e.g. empty or null values) and ensure proper error handling.\n\n*Analyzed by @devsup-ai engine.*`;
        res.json({ reply: explanation, model: 'devsup-ai-engine', fallback: true });
    }
});

