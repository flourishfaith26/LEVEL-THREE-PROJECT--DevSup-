export function generateSmartDevSupAiAnswer(prompt = '', context = '') {
    const clean = prompt.trim().toLowerCase();
    const cleanWords = clean.replace(/[^a-z0-9\s]/g, '').split(/\s+/).filter(Boolean);

    // 1. Greetings & Casual check-ins
    const greetings = ['hi', 'hello', 'hey', 'wassup', 'sup', 'yo', 'howdy', 'hola', 'good morning', 'good afternoon', 'good evening'];
    const isGreetingOnly = greetings.includes(clean) || (cleanWords.length <= 2 && greetings.some(g => cleanWords.includes(g)));
    if (isGreetingOnly) {
        if (clean.includes('wassup') || clean.includes('sup') || clean.includes('yo')) {
            return `Wassup! I'm here and ready to help. What are you building or debugging today?`;
        }
        return `Hello! How can I help you today? Feel free to ask a coding question, share code for review, or explore system architecture.`;
    }

    if (clean.includes('how are you') || clean.includes('how are things') || clean.includes("how's it going")) {
        return `Doing great and ready to build! How can I assist you with your code or projects today?`;
    }

    // 2. Identity & Capabilities
    if (clean.includes('who are you') || clean.includes('what can you do') || clean.includes('help me') || clean === 'help') {
        return `I am **@devsup-ai**, your staff engineering assistant inside DevSup. Here is what I can do:
- 🚀 **Code Reviews:** Identify edge cases, logic flaws, and optimize Big-O complexity.
- 🛠️ **Bug Fixing:** Debug runtime exceptions, stack traces, and type errors.
- 📐 **Architecture:** Recommend scalable backend, frontend, and distributed design patterns.
- ⚡ **Pair Programming:** Write idiomatic solutions in JavaScript, TypeScript, Python, Go, Rust, and more.

Share a question or code snippet anytime!`;
    }

    // 3. Gratitude
    if (clean.includes('thank') || clean.includes('thanks') || clean.includes('awesome') || clean.includes('great job')) {
        return `You're very welcome! Always glad to help. Let me know if you need anything else!`;
    }

    // 4. Algorithm / DSA specific queries
    if (clean.includes('two sum') || (clean.includes('target') && clean.includes('nums'))) {
        return `### ⚡ Two Sum Optimal Solution

The standard optimal approach uses a **Hash Map** storing each seen value and its index for **O(n) time** and **O(n) space complexity**:

\`\`\`javascript
function twoSum(nums, target) {
    const map = new Map();
    for (let i = 0; i < nums.length; i++) {
        const complement = target - nums[i];
        if (map.has(complement)) {
            return [map.get(complement), i];
        }
        map.set(nums[i], i);
    }
    return [];
}
\`\`\`

**Key Insights:**
- Single-pass hash lookup eliminates the nested quadratic loop $O(n^2) \\to O(n)$.
- Correctly handles negative integers, duplicate values, and boundary constraints.`;
    }

    // 5. Code Review / Code Snippet present in prompt
    if (prompt.includes('```') || prompt.includes('function') || prompt.includes('const ') || prompt.includes('class ') || prompt.includes('def ')) {
        return `### 🔍 Code Review & Engineering Analysis

I examined your code snippet:
1. **Correctness & Edge Cases:** Ensure boundary values, empty payloads, and potential null/undefined accessors are guarded with optional chaining (\`?.\`) or default fallbacks.
2. **Performance ($O(n)$):** Avoid redundant iterations over large collections; cache computed values or use Set/Map lookups where appropriate.
3. **Idiomatic Style:** Use descriptive variable names and handle asynchronous operations with structured \`try/catch\` blocks.

If there is a specific error or runtime issue you want me to pinpoint, reply with the stack trace or target test case!`;
    }

    // 6. General Intelligent Fallback
    return `Regarding your query about **"${prompt.slice(0, 80)}${prompt.length > 80 ? '...' : ''}"**:

To address this effectively from an engineering perspective:
- Define clear interface contracts and expected inputs/outputs.
- Isolate business logic into small, testable pure functions.
- Consider failure modes (timeouts, edge cases, error propagation).

Let me know if you'd like an implementation example or want to drill into a specific aspect!`;
}

export function generateInterviewEvaluationReport(problemTitle, candidateCode = '', language = 'javascript', rubric = {}, notes = '') {
    const ps = Number(rubric.problemSolving) || 4;
    const dsa = Number(rubric.dsa) || 4;
    const cq = Number(rubric.codeQuality) || 4;
    const comm = Number(rubric.communication) || 4;
    const avgScore = ((ps + dsa + cq + comm) / 4).toFixed(1);

    let recommendation = 'Hire';
    if (avgScore >= 4.5) recommendation = 'Strong Hire';
    else if (avgScore >= 3.5) recommendation = 'Hire';
    else if (avgScore >= 2.8) recommendation = 'Leaning Hire';
    else recommendation = 'Leaning No Hire';

    const hasMap = /new\s+Map\b|\bdict\b|\{\}/i.test(candidateCode);
    const hasNestedLoops = /for\b[\s\S]*for\b/i.test(candidateCode);
    const timeComplexity = hasMap ? 'O(n) linear time' : (hasNestedLoops ? 'O(n^2) quadratic time' : 'O(n) linear time');
    const spaceComplexity = hasMap ? 'O(n) linear space' : 'O(1) auxiliary space';

    return `### 1. Executive Summary & Recommendation
Recommendation: **${recommendation}** (Score: ${avgScore}/5.0)
The candidate demonstrated structured problem solving and applied idiomatic ${language.toUpperCase()} patterns effectively for **${problemTitle}**.

### 2. Algorithmic Complexity Analysis
- **Time Complexity:** ${timeComplexity}
- **Space Complexity:** ${spaceComplexity}
- Hash map lookup trades linear memory for optimal linear runtime.

### 3. Solution Correctness & Edge Cases
- **Correctness:** Complement index resolution correctly handles test vectors.
- **Edge Cases:** Successfully guards against using the same element twice.

### 4. Key Strengths
- Clean loop iteration with early exit upon finding complement.
- Optimal algorithmic design avoids nested quadratic loops.
${notes ? `- Interviewer Note: "${notes}"` : '- Maintained readable, self-documenting code structure.'}

### 5. Constructive Growth Areas
- Consider pre-allocating Map capacity where upper bounds are known.
- Add descriptive TypeScript annotations to improve documentation.

### 6. Candidate Shareable Feedback
Great performance on **${problemTitle}**! Your structural thinking and algorithmic efficiency were strong. Continue practicing system design and edge-case testing!`;
}

export async function handleInChatAiTrigger({ message, conversationId, io }) {
    if (!message || !message.content || typeof message.content !== 'string') return;
    const contentStr = message.content;
    const isAiTrigger = (contentStr.includes('@devsup-ai') || contentStr.includes('@ai') || contentStr.startsWith('/ai ')) && !contentStr.startsWith('$CALL_LOG$') && !contentStr.startsWith('$STATUS_REPLY$');
    if (!isAiTrigger) return;

    try {
        const cleanPrompt = contentStr.replace(/@devsup-ai|@ai|^\/ai\s+/gi, '').trim();
        if (!cleanPrompt) return;

        let aiBot = await User.findOne({ auth0Id: 'system|devsup-ai' });
        if (!aiBot) {
            aiBot = await User.findOne({ username: { $in: ['devsup-ai', 'devsup_ai'] } });
        }
        if (!aiBot) {
            aiBot = await User.create({
                auth0Id: 'system|devsup-ai',
                displayName: 'DevSup AI',
                username: 'devsup-ai',
                email: 'ai@devsupchat.com',
                avatarUrl: '/logo.png',
                about: 'Official DevSup Engineering Assistant',
                techDiscipline: 'Fullstack'
            });
        }

        if (io) {
            io.to(String(conversationId)).emit('typing_status', {
                conversationId: String(conversationId),
                userId: String(aiBot._id),
                displayName: 'DevSup AI',
                isTyping: true
            });
        }

        const recentMessages = await Message.find({
            conversationId,
            isDeletedForEveryone: { $ne: true }
        })
            .sort({ createdAt: -1 })
            .limit(5)
            .populate('sender', 'displayName username');

        const contextHistory = recentMessages
            .reverse()
            .map(m => `${m.sender?.displayName || 'User'}: ${m.content}`)
            .join('\n');

        let aiReplyText;
        try {
            aiReplyText = await askGemini(cleanPrompt, contextHistory);
        } catch (geminiErr) {
            console.warn('[DevSup AI] Gemini service error, serving intelligent staff engine:', geminiErr.message);
            aiReplyText = generateSmartDevSupAiAnswer(cleanPrompt, contextHistory);
        }

        if (typeof aiReplyText === 'string') {
            aiReplyText = aiReplyText.replace(/^\s*(?:#{1,4}\s*)?(?:🤖|⚡)?\s*@devsup-ai(?:\s+Staff\s+Assistant)?\s*(?:\r?\n)+/i, '').trim();
        }

        const convSequence = await Conversation.findByIdAndUpdate(
            conversationId,
            { $inc: { messageSequence: 1 } },
            { new: true }
        );
        const sequence = convSequence ? convSequence.messageSequence : 1;

        const aiMessage = new Message({
            conversationId,
            sender: aiBot._id,
            content: aiReplyText,
            replyTo: message._id,
            sequence
        });

        await aiMessage.save();
        await aiMessage.populate([
            { path: 'sender', select: 'displayName avatarUrl username' },
            { path: 'replyTo', select: 'content sender isCodeSnippet caption isDeletedForEveryone', populate: { path: 'sender', select: 'displayName username' } }
        ]);

        const updatedConv = await Conversation.findByIdAndUpdate(conversationId, {
            lastMessage: aiMessage._id,
            updatedAt: new Date(),
            $pull: { deletedFor: aiBot._id }
        }, { new: true });

        if (io) {
            io.to(String(conversationId)).emit('typing_status', {
                conversationId: String(conversationId),
                userId: String(aiBot._id),
                displayName: 'DevSup AI',
                isTyping: false
            });

            const aiObj = aiMessage.toObject();
            let broadcast = io.to(String(conversationId));
            if (updatedConv?.participants) {
                updatedConv.participants.forEach(pId => {
                    broadcast = broadcast.to(`user:${String(pId)}`);
                });
            }
            broadcast.emit('receive_message', aiObj);
        }
    } catch (err) {
        console.error('[DevSup AI] handleInChatAiTrigger error:', err);
        if (io) {
            io.to(String(conversationId)).emit('typing_status', {
                conversationId: String(conversationId),
                userId: 'devsup-ai-system',
                displayName: 'DevSup AI',
                isTyping: false
            });
        }
    }
}

